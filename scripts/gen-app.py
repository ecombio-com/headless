# Generates src/app/** (pages + route handlers) and src/server/registry.ts from src/routes/*.
# Re-run after adding a route folder:  python scripts/gen-app.py
import os, re, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROUTES = os.path.join(ROOT, 'src', 'routes')
APP = os.path.join(ROOT, 'src', 'app')
NO_LOCALE = {'api.checkout-status', 'api.checkout-url', 'api.checkout.sessions', 'api.stripe.webhook', 'robots.txt', 'sitemap.xml', 'sitemap.$type.$page.xml', 'sitemap.xsl'}
# Loader-only routes and routes that must set cookies become route handlers.
# Pages that use the focused checkout layout; every other page uses the shop layout.
CHECKOUT = {'cart', 'address', 'payment', 'payment_.complete'}
FORCE_HANDLER = {'cart.$lines', 'discount.$code', 'account._index', 'checkout._index'}
SPECIAL = {'sitemap.xml': ['sitemap.xml'], 'robots.txt': ['robots.txt'], 'sitemap.$type.$page.xml': ['sitemap', '$type', '$page'], 'sitemap.xsl': ['sitemap.xsl']}

def segments(name):
    if name in SPECIAL: return SPECIAL[name]
    out = []
    for part in name.split('.'):
        if part == '_index': continue
        out.append(part.rstrip('_') if part not in ('$',) else '$')
    return out

def folder(seg):
    if seg == '$': return '[...slug]'
    if seg.startswith('$'): return '[' + seg[1:] + ']'
    return seg

def pattern(seg):
    if seg == '$': return '*'
    if seg.startswith('$'): return ':' + seg[1:]
    return seg

registry = []
generated = []
for name in sorted(os.listdir(ROUTES)):
    d = os.path.join(ROUTES, name)
    if not os.path.isdir(d): continue
    has_view = os.path.exists(os.path.join(d, 'view.tsx'))
    if has_view and re.search(r"export default function \w*\(\) \{\s*return null;\s*\}", open(os.path.join(d, 'view.tsx')).read()):
        has_view = False
    if name in FORCE_HANDLER: has_view = False
    segs = segments(name)
    locale = name not in NO_LOCALE
    is_layout = name == 'account'
    url = ('/:locale' if locale else '') + ''.join('/' + pattern(s) for s in segs)
    imp = f"~/routes/{name}/server"
    if not is_layout: registry.append((url, imp))
    group = []
    if locale and (has_view or is_layout or name == '$'):
        group = ['(checkout)' if name in CHECKOUT else '(shop)']
    target = os.path.join(APP, *(['[locale]'] if locale else []), *group, *[folder(s) for s in segs])
    os.makedirs(target, exist_ok=True)
    if name == '$':
        path = os.path.join(target, 'page.tsx')
        open(path, 'w').write("// Generated by scripts/gen-app.py: unknown URLs render the 404 page.\nimport {notFound} from 'next/navigation';\n\nexport default function CatchAll() {\n  notFound();\n}\n")
        generated.append(os.path.relpath(path, ROOT))
        continue
    if is_layout:
        path = os.path.join(target, 'layout.tsx')
        code = f"""// Generated by scripts/gen-app.py from src/routes/{name}.
import type {{ReactNode}} from 'react';
import * as mod from '{imp}';
import View from '~/routes/{name}/view';
import {{renderLayout}} from '~/server/route';

export default function Layout({{children, params}}: {{children: ReactNode; params: Promise<Record<string, string | string[] | undefined>>}}) {{
  return renderLayout(mod, View, params, children);
}}
"""
    elif has_view:
        path = os.path.join(target, 'page.tsx')
        code = f"""// Generated by scripts/gen-app.py from src/routes/{name}.
import * as mod from '{imp}';
import View from '~/routes/{name}/view';
import {{renderRoute}} from '~/server/route';

export default function Page({{params}}: {{params: Promise<Record<string, string | string[] | undefined>>}}) {{
  return renderRoute(mod, View, params);
}}
"""
    else:
        path = os.path.join(target, 'route.ts')
        code = f"""// Generated by scripts/gen-app.py from src/routes/{name}.
import * as mod from '{imp}';
import {{resourceRoute}} from '~/server/resource';

export const {{GET, POST, PUT, PATCH, DELETE}} = resourceRoute(mod);
"""
    open(path, 'w').write(code)
    generated.append(os.path.relpath(path, ROOT))

# Specific patterns first (static segments beat params beat splats).
def rank(p):
    return [0 if not s.startswith((':', '*')) else (1 if s.startswith(':') else 2) for s in p.split('/')[1:]] + [len(p.split('/'))]
registry.sort(key=lambda r: (r[0].count('*'), -len(r[0].split('/')), rank(r[0])))
lines = ["// Generated by scripts/gen-app.py: URL pattern -> route module (loader/action).", "export const ROUTES: [string, () => Promise<any>][] = ["]
for url, imp in registry:
    lines.append(f"  [{json.dumps(url)}, () => import('{imp}')],")
lines.append("];")
open(os.path.join(ROOT, 'src', 'server', 'registry.ts'), 'w').write('\n'.join(lines) + '\n')
print('\n'.join(generated))
